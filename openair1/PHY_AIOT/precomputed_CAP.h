const c16_t *CAP_SCs_select(int RBs, int M, bool ZC_Ones) {
  if(M != 1 && M != 2 && M != 4) AssertFatal(1==0,"Unknown M %d",M);
  switch (RBs) {
    case 1:
      switch (M) {
        case 1:
          return ZC_Ones ? CAP_SCs_ZC_1RBs_M1 : CAP_SCs_Ones_1RBs_M1;
        case 2:
          return ZC_Ones ? CAP_SCs_ZC_1RBs_M2 : CAP_SCs_Ones_1RBs_M2;
        case 4:
          return ZC_Ones ? CAP_SCs_ZC_1RBs_M4 : CAP_SCs_Ones_1RBs_M4;
      }
    case 2:
      switch (M) {
        case 1:
          return ZC_Ones ? CAP_SCs_ZC_2RBs_M1 : CAP_SCs_Ones_2RBs_M1;
        case 2:
          return ZC_Ones ? CAP_SCs_ZC_2RBs_M2 : CAP_SCs_Ones_2RBs_M2;
        case 4:
          return ZC_Ones ? CAP_SCs_ZC_2RBs_M4 : CAP_SCs_Ones_2RBs_M4;
      }
    case 4:
      switch (M) {
        case 1:
          return ZC_Ones ? CAP_SCs_ZC_4RBs_M1 : CAP_SCs_Ones_4RBs_M1;
        case 2:
          return ZC_Ones ? CAP_SCs_ZC_4RBs_M2 : CAP_SCs_Ones_4RBs_M2;
        case 4:
          return ZC_Ones ? CAP_SCs_ZC_4RBs_M4 : CAP_SCs_Ones_4RBs_M4;
      }
    default:
      AssertFatal(1==0,"Unknown N_PRB");
  }
}

