const c16_t *CAP_SCs_select(int RBs, int M, bool ZC_Ones) {
  if(M != 1 && M != 2 && M != 4) AssertFatal(1==0,"Unknown M %d",M);
  switch (RBs) {
    case 1:
      switch (M) {
        case 1:
          return ZC_Ones ? CAP_SCs_ZC_1RBs_M1 : CAP_SCs_Ones_1RBs_M1;
        case 2:
          return ZC_Ones ? CAP_SCs_ZC_1RBs_M2 : CAP_SCs_Ones_1RBs_M2;
        case 4:
          return ZC_Ones ? CAP_SCs_ZC_1RBs_M4 : CAP_SCs_Ones_1RBs_M4;
      }
    case 6:
      switch (M) {
        case 1:
          return ZC_Ones ? CAP_SCs_ZC_6RBs_M1 : CAP_SCs_Ones_6RBs_M1;
        case 2:
          return ZC_Ones ? CAP_SCs_ZC_6RBs_M2 : CAP_SCs_Ones_6RBs_M2;
        case 4:
          return ZC_Ones ? CAP_SCs_ZC_6RBs_M4 : CAP_SCs_Ones_6RBs_M4;
      }
    case 25:
      switch (M) {
        case 1:
          return ZC_Ones ? CAP_SCs_ZC_25RBs_M1 : CAP_SCs_Ones_25RBs_M1;
        case 2:
          return ZC_Ones ? CAP_SCs_ZC_25RBs_M2 : CAP_SCs_Ones_25RBs_M2;
        case 4:
          return ZC_Ones ? CAP_SCs_ZC_25RBs_M4 : CAP_SCs_Ones_25RBs_M4;
      }
    default:
      AssertFatal(1==0,"Unknown N_PRB");
  }
}

